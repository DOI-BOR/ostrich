/**************************************************************************************************************************************************************

Parallel Dynamically Dimensioned Search (PDDS) algorithm. PDDS is a parallel version of the DDS algorithm described in Tolson and Shoemaker (2007), Water
Resources Research. Candidate solutions are generated by perturbing a randomly selected subset of the decision variables of the current best solution, with
the expected number of perturbed variables decreasing as the search budget is consumed. A candidate replaces the current best if its objective is no worse.

The pre-refactor implementation farmed candidates out to the secondary workers asynchronously, generating each new candidate from the best solution known
when a worker became free. The Algorithm base class solves sets of parameter sets, so this version generates a batch of candidates from the current best
solution (one per available worker), solves the batch in parallel, and then processes the results in the order that the candidates were generated. This
keeps every worker busy while making the search independent of the order in which the workers finish.

Original C++ port by L. Shawn Matott (2014) of Bryan Tolson's parallel Fortran DDS code.

**************************************************************************************************************************************************************/

