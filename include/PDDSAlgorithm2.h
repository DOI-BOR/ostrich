#include "Exception.h"
#include "Utility.h"


class PDDSAlgorithm : public Algorithm {
    public:
        // Define constructors and destructors
        PDDSAlgorithm();
        ~PDDSAlgorithm(void) { DBG_PRINT("PDDSAlgorithm::DTOR"); Destroy(); }
        void Destroy(void);

        // Solution functions
        void Optimize(void);                                                // Function to optimize a solution using PDDS

        // Output functions
        void WriteStartingMetrics(void);                                    // Function to write the starting PDDS metrics
        void WriteEndingMetrics(void);                                      // Function to write the ending PDDS metrics

    private:
        // Configuration variables
        double m_r_val = 0.2;                                               // Perturbation value (0 < r < 1), as a fraction of the parameter range
        int m_MaxIter = 100;                                                // Maximum number of objective function evaluations
        bool m_UserSuppliedInit = false;                                    // true: start from user-supplied values, false: random initialization
        std::string m_UseOpt = "standard";                                  // Special user option: standard, no-rand-num, or try-int-solution
        double m_alpha = 0.5;                                               // Perturbation probability used by the no-rand-num option
        double m_beta = 0.5;                                                // Perturbation multiplier used by the no-rand-num option
        bool m_bDebug = false;                                              // Write debugging information to the console
        std::vector<std::vector<double>> m_InitParams;                      // User-supplied initial parameter sets (BeginInitParams), transformed

        // Solution tracking variables
        int m_CurIter = 0;                                                  // Number of objective function evaluations performed
        int m_BatchSize = 1;                                                // Number of candidates solved concurrently

        // Solution functions
        std::vector<double> Evaluate(std::vector<std::vector<double>> samples); // Function to solve a set of parameter sets and track the best solution
        std::vector<double> CorrectParameters(std::vector<double> parameters); // Function to apply any parameter corrections
        double PerturbParam(double x_cur, ParameterABC* pParam);            // Function to generate a neighboring value for a single parameter
        void SetParameterGroup(std::vector<double> parameters);             // Function to set values into the parameter group
        void ReadInitParams(FILE* pFile, IroncladString inputFilename);     // Function to read the user-supplied initial parameter sets
        void WriteStatus(int evaluation, double objective, std::vector<double> parameters); // Function to append the current best to dds_status.out
};

extern "C" {
void PDDS_Program(int argC, StringType argV[]);
}

#endif /* PDDS_ALGORITHM_H */
