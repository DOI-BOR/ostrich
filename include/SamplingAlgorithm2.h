/**************************************************************************************************************************************************************

An implementation of a sampling algorithm, loosely based on Big Bang-Big Crunch (BB-BC). An initial set of Latin Hypercube samples is evaluated, and each
subsequent iteration samples the space around the current best solution using a search radius that shrinks as the analysis progresses. The samples of each
iteration are solved using the shared, asynchronous MPI work-farming functionality provided by the Algorithm base class.

**************************************************************************************************************************************************************/

#ifndef SAMPLING_ALGORITHM_H
#define SAMPLING_ALGORITHM_H

// Include C classes
#include <mpi.h>
#include <math.h>
#include <stdlib.h>

// Include C++ classes
#include <algorithm>
#include <vector>
#include <iostream>

// Include custom classes
#include "MyHeaderInc.h"
#include "Algorithm.h"
#include "LatinHypercube.h"
#include "ParameterGroup.h"
#include "ReadUtility.h"
#include "ParameterABC.h"
#include "Exception.h"
#include "Utility.h"


class SamplingAlgorithm : public Algorithm {
   public:
        // Define constructors and destructors
        SamplingAlgorithm();
        ~SamplingAlgorithm(void){ DBG_PRINT("SamplingAlgorithm::DTOR"); Destroy(); }
        void Destroy(void);

        // Define sampling functions used by the sampling algorithm
        std::vector<std::vector<double>> CreateInitialSample(int sampleSize);    // Function to create the initial Latin Hypercube sample
        std::vector<std::vector<double>> CreateSample(int sampleSize);           // Function to create a sample around the current best solution

        // Solution functions
        void Optimize(void);                                                // Function to optimize a solution using the sampling algorithm

        // Output functions
        void WriteStartingMetrics(void);                                     // Function to write the starting sampling metrics
        void WriteEndingMetrics(void);                                       // Function to write the ending sampling metrics

   private:
        // Configuration variables
        int m_MaxEvals = 100;                                               // Targeted maximum number of model evaluations
        double m_Radius = 4.00;                                             // Search radius, in units of the parameter standard deviations

        // Sampling schedule, derived from m_MaxEvals
        int m_MaxIter = 10;                                                 // Maximum number of iterations [sqrt(m_MaxEvals)]
        int m_NumSamples = 10;                                              // Number of samples per iteration [m_MaxEvals / m_MaxIter]
        int m_NumExtra = 0;                                                 // Number of extra initial samples [m_MaxEvals - (m_MaxIter * m_NumSamples)]

        // Sampling state - one entry per parameter
        std::vector<double> m_Lwr;                                          // Lower bound (transformed) for each parameter
        std::vector<double> m_Upr;                                          // Upper bound (transformed) for each parameter
        std::vector<double> m_SD;                                           // Parameter standard deviations
        std::vector<double> m_Fwd;                                          // Forward perturbation weights (probability that dX is positive)

        // Solution tracking variables
        int m_CurIter = 0;                                                  // Counter for the current iteration number
        int m_AlgCount = 0;                                                 // Number of samples generated by the algorithm

        // Solution functions
        void UpdateBest(std::vector<std::vector<double>> samples, std::vector<double> objectives); // Updates the best solution, standard deviations and weights

};

extern "C" {
void SMP_Program(int argC, StringType argV[]);
}

#endif
