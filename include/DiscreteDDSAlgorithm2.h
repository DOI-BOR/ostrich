#include <iostream>

// Include custom classes
#include "MyHeaderInc.h"
#include "Algorithm.h"
#include "ParameterGroup.h"
#include "ReadUtility.h"
#include "ParameterABC.h"
#include "Exception.h"
#include "Utility.h"


class DiscreteDDSAlgorithm : public Algorithm {
    public:
        // Define constructors and destructors
        DiscreteDDSAlgorithm();
        ~DiscreteDDSAlgorithm(void) { DBG_PRINT("DiscreteDDSAlgorithm::DTOR"); Destroy(); }
        void Destroy(void);

        // Solution functions
        void Optimize(void);                                                // Function to optimize a solution using Discrete DDS

        // Output functions
        void WriteStartingMetrics(void);                                    // Function to write the starting Discrete DDS metrics
        void WriteEndingMetrics(void);                                      // Function to write the ending Discrete DDS metrics

    private:
        // Configuration variables
        double m_r_val = 0.2;                                               // Perturbation value (0 < r < 1), as a fraction of the parameter range
        int m_MaxIter = 100;                                                // Maximum number of objective function evaluations
        bool m_UserSuppliedInit = false;                                    // true: start from the initial parameter values, false: random initialization

        // Solution tracking variables
        int m_CurIter = 0;                                                  // Number of objective function evaluations performed
        int m_nCorr = 0;                                                    // Number of perturbations corrected to force a discrete change

        // Solution functions
        std::vector<double> Evaluate(std::vector<std::vector<double>> samples); // Function to solve a set of parameter sets and track the best solution
        double PerturbParam(double x_best, ParameterABC* pParam);           // Function to generate a neighboring value for a single parameter
        void SetParameterGroup(std::vector<double> parameters);             // Function to set values into the parameter group
        std::vector<double> ApplyParameterGroup(std::vector<double> parameters); // Function to return a parameter set as stored by the parameter group
};

extern "C" {
void DiscreteDDS_Program(int argC, StringType argV[]);
}

