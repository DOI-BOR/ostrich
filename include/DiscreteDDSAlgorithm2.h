/**************************************************************************************************************************************************************

Discrete Dynamically Dimensioned Search (DDDS) algorithm. A variant of the DDS algorithm of Tolson and Shoemaker (2007), Water Resources Research, intended for
discrete-valued decision variables. Candidate solutions are generated by perturbing a randomly selected subset of the decision variables of the current best
solution, and each perturbation is forced to change the value of the decision variable by at least one unit. A candidate replaces the current best if its
objective is no worse.

The search is initialized from either the user-supplied parameter values, the best solution of a previous run (warm start), or the best of a set of uniform
random samples. The random initialization samples are independent and are solved together using the shared, asynchronous MPI work-farming functionality
provided by the Algorithm base class. The main search loop is inherently sequential, as each candidate is generated from the current best solution.

Original implementation by L. Shawn Matott (2011).

**************************************************************************************************************************************************************/

