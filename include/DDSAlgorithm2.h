/**************************************************************************************************************************************************************

Dynamically Dimensioned Search (DDS) algorithm, as described in Tolson and Shoemaker (2007), Water Resources Research. DDS is a greedy, single-solution global
search. Candidate solutions are generated by perturbing a randomly selected subset of the decision variables of the current best solution, with the expected
number of perturbed variables decreasing as the search budget is consumed. A candidate replaces the current best if its objective is no worse.

The search is initialized from either the user-supplied parameter values, the best solution of a previous run (warm start), or the best of a set of uniform
random samples. The random initialization samples are independent and are solved together using the shared, asynchronous MPI work-farming functionality
provided by the Algorithm base class. The main search loop is inherently sequential, as each candidate is generated from the current best solution.

Original C++ translation by James Craig (2006) of Bryan Tolson's Fortran DDS code.

**************************************************************************************************************************************************************/

